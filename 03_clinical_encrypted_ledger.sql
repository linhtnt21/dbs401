USE HospitalZT;
SET XACT_ABORT ON;
IF NOT EXISTS(SELECT 1 FROM sys.column_encryption_keys WHERE name=N'CEK_Hospital') THROW 50002, 'Create CEK_Hospital on application machine first. Read README.', 1;
BEGIN TRAN;
CREATE TABLE dbo.Patients (
    PatientId int IDENTITY PRIMARY KEY,
    PatientCode varchar(20) UNIQUE NOT NULL,
    FullName nvarchar(100) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    DateOfBirth date ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Gender nvarchar(20) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    NationalId nvarchar(20) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Phone nvarchar(20) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Address nvarchar(300) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    InsuranceNumber nvarchar(30) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    EmergencyContact nvarchar(200) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    CreatedAt datetime2 NOT NULL DEFAULT SYSUTCDATETIME()
) WITH (SYSTEM_VERSIONING=ON (HISTORY_TABLE=dbo.PatientsHistory), LEDGER=ON (LEDGER_VIEW=dbo.PatientsLedgerView));

CREATE TABLE dbo.Encounters (
    EncounterId int IDENTITY PRIMARY KEY,
    PatientId int NOT NULL REFERENCES dbo.Patients(PatientId),
    DepartmentId int NOT NULL REFERENCES dbo.Departments(DepartmentId),
    DoctorId int NOT NULL REFERENCES dbo.Staff(StaffId),
    VisitTime datetime2 NOT NULL DEFAULT SYSUTCDATETIME(),
    Status varchar(20) NOT NULL DEFAULT 'OPEN',
    ReasonForVisit nvarchar(500) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    UNIQUE(EncounterId,DepartmentId)
) WITH (SYSTEM_VERSIONING=ON (HISTORY_TABLE=dbo.EncountersHistory), LEDGER=ON (LEDGER_VIEW=dbo.EncountersLedgerView));

CREATE TABLE dbo.MedicalRecords (
    RecordId int IDENTITY PRIMARY KEY,
    EncounterId int NOT NULL UNIQUE,
    DepartmentId int NOT NULL,
    Symptoms nvarchar(500) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Diagnosis nvarchar(500) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    TreatmentPlan nvarchar(1000) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Allergies nvarchar(500) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    ClinicalNotes nvarchar(2000) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    UpdatedAt datetime2 NOT NULL DEFAULT SYSUTCDATETIME(),
    FOREIGN KEY(EncounterId,DepartmentId) REFERENCES dbo.Encounters(EncounterId,DepartmentId),
    UNIQUE(RecordId,DepartmentId)
) WITH (SYSTEM_VERSIONING=ON (HISTORY_TABLE=dbo.MedicalRecordsHistory), LEDGER=ON (LEDGER_VIEW=dbo.MedicalRecordsLedgerView));

CREATE TABLE dbo.Prescriptions (
    PrescriptionId int IDENTITY PRIMARY KEY,
    RecordId int NOT NULL,
    DepartmentId int NOT NULL,
    PrescribedAt datetime2 NOT NULL DEFAULT SYSUTCDATETIME(),
    Instructions nvarchar(500) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    FOREIGN KEY(RecordId,DepartmentId) REFERENCES dbo.MedicalRecords(RecordId,DepartmentId),
    UNIQUE(PrescriptionId,DepartmentId)
) WITH (SYSTEM_VERSIONING=ON (HISTORY_TABLE=dbo.PrescriptionsHistory), LEDGER=ON (LEDGER_VIEW=dbo.PrescriptionsLedgerView));

CREATE TABLE dbo.PrescriptionItems (
    PrescriptionItemId int IDENTITY PRIMARY KEY,
    PrescriptionId int NOT NULL,
    DepartmentId int NOT NULL,
    MedicationName nvarchar(100) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Dosage nvarchar(100) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Frequency nvarchar(100) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Duration nvarchar(100) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Quantity int ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    FOREIGN KEY(PrescriptionId,DepartmentId) REFERENCES dbo.Prescriptions(PrescriptionId,DepartmentId)
) WITH (SYSTEM_VERSIONING=ON (HISTORY_TABLE=dbo.PrescriptionItemsHistory), LEDGER=ON (LEDGER_VIEW=dbo.PrescriptionItemsLedgerView));

CREATE TABLE dbo.LabOrders (
    LabOrderId int IDENTITY PRIMARY KEY,
    EncounterId int NOT NULL,
    DepartmentId int NOT NULL,
    TestName nvarchar(100) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    ClinicalIndication nvarchar(500) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    OrderedAt datetime2 NOT NULL DEFAULT SYSUTCDATETIME(),
    Status varchar(20) NOT NULL DEFAULT 'ORDERED',
    FOREIGN KEY(EncounterId,DepartmentId) REFERENCES dbo.Encounters(EncounterId,DepartmentId),
    UNIQUE(LabOrderId,DepartmentId)
) WITH (SYSTEM_VERSIONING=ON (HISTORY_TABLE=dbo.LabOrdersHistory), LEDGER=ON (LEDGER_VIEW=dbo.LabOrdersLedgerView));

CREATE TABLE dbo.LabResults (
    LabResultId int IDENTITY PRIMARY KEY,
    LabOrderId int NOT NULL UNIQUE,
    DepartmentId int NOT NULL,
    ResultValue nvarchar(200) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    ReferenceRange nvarchar(100) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    Conclusion nvarchar(1000) COLLATE Latin1_General_100_BIN2 ENCRYPTED WITH (COLUMN_ENCRYPTION_KEY=CEK_Hospital, ENCRYPTION_TYPE=RANDOMIZED, ALGORITHM='AEAD_AES_256_CBC_HMAC_SHA_256') NULL,
    ReportedAt datetime2 NOT NULL DEFAULT SYSUTCDATETIME(),
    FOREIGN KEY(LabOrderId,DepartmentId) REFERENCES dbo.LabOrders(LabOrderId,DepartmentId)
) WITH (SYSTEM_VERSIONING=ON (HISTORY_TABLE=dbo.LabResultsHistory), LEDGER=ON (LEDGER_VIEW=dbo.LabResultsLedgerView));

COMMIT;
